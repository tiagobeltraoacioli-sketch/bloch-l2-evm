#!/usr/bin/env python3
"""Generate the public variant of a private operator runbook.

The private runbook stays the only source. This script derives the public copy from it by replacing
operator hosts, process IDs, home directories, local workspace paths and key paths with placeholders,
then runs publish_check's rules over the result and refuses to write a file that still has a
blocking hit or a host path.

  redact_runbook.py                 regenerate every pair in public-variants.txt
  redact_runbook.py --check         exit 1 if a committed public variant is stale or unsafe
  redact_runbook.py SRC DEST        one pair

Host roles come from a PRIVATE map (never committed; default
~/.config/bloch-publish-safety/host-roles.conf, or --hosts / $BLOCH_PUBLISH_HOSTS). Each line is
`<literal>\t<PLACEHOLDER>` or `re:<python regex>\t<PLACEHOLDER>`; the placeholder is written as
`<PLACEHOLDER>`. Paths matching the denylist's [key-path] patterns become `<KEY_PATH>` (map a key
path explicitly to name it, e.g. SSH_KEY). Addresses in publish-allowlist.txt (the public RPC endpoints) are kept. Any other
IPv4 address that the map does not name becomes `<HOST_n>` in order of first appearance, so a
host missing from the map is still hidden. The private denylist (see publish_check.py) is used for
the final check when present; --check and the default mode require it.
"""
import argparse
import hashlib
import ipaddress
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import publish_check as pc  # noqa: E402

DEFAULT_HOSTS = os.path.expanduser('~/.config/bloch-publish-safety/host-roles.conf')
MANIFEST = os.path.join(HERE, 'public-variants.txt')

PID_LINE = re.compile(r'(?i)\bpids?\b|\bkill\b|ps\s+-o\s+pid|pgrep|\bpid=')
PID_NUM = re.compile(r'(?<![\w.:/-])\d{5,8}(?![\w.:/-]*\d)')
GENERIC = [
    (re.compile(r'/home/ubuntu\b'), '/home/<operator>'),
    (re.compile(r'\bubuntu@'), '<operator>@'),
    (re.compile(r'/Users/[\w.-]+'), '<local-home>'),
    (re.compile(r'~/Desktop/[^\s`\'")\]]+'), '<owner-workspace>'),
    (re.compile(r'(?:~/)?l2dexbridge-\d{8}'), '<scratch-dir>'),
    (re.compile(r'(?<![\w/-])agents/\d{1,3}-[\w.-]+(?:\.md)?'), '<internal-report>'),
    (re.compile(r'[\w.-]+\.(?:lan|local)\b'), '<local-host>'),
]


def load_hosts(path):
    rules = []
    with open(path) as fh:
        for raw in fh:
            line = raw.rstrip('\n')
            if not line.strip() or line.lstrip().startswith('#'):
                continue
            key, sep, placeholder = line.partition('\t')
            if not sep or not re.fullmatch(r'[A-Z][A-Z0-9_]*', placeholder.strip()):
                raise SystemExit(f'{path}: each line is <literal or re:regex><TAB><PLACEHOLDER>')
            if key.startswith('re:'):
                rx = re.compile(key[3:])
            else:
                rx = re.compile(r'(?<![\w.])' + re.escape(key) + r'(?![\w]|\.\d)')
            rules.append((len(key), rx, '<' + placeholder.strip() + '>'))
    rules.sort(key=lambda r: -r[0])
    return [(rx, ph) for _, rx, ph in rules]


def redact(text, host_rules, cfg):
    out_lines = []
    numbered = {}
    for line in text.split('\n'):
        for rx, ph in host_rules:
            line = rx.sub(ph, line)
        # Key folders come from the private denylist ([key-path]); the whole path token goes.
        for pat in cfg.key_paths:
            line = re.sub(r'[^\s`\'"()\[\]<>]*(?:' + pat.rx.pattern + r')[^\s`\'"()\[\]<>]*', '<KEY_PATH>', line,
                          flags=re.I)
        for rx, ph in GENERIC:
            line = rx.sub(ph, line)

        def host(m):
            ip = m.group(1)
            addr = ipaddress.ip_address(ip)
            if any(addr in n for n in cfg.allow_ips):
                return ip
            if ip not in numbered:
                numbered[ip] = f'<HOST_{len(numbered) + 1}>'
            return numbered[ip]
        line = pc.IPV4.sub(host, line)
        if PID_LINE.search(line):
            line = PID_NUM.sub('<PID>', line)
        out_lines.append(line)
    return '\n'.join(out_lines)


def header(src, data):
    digest = hashlib.sha256(data.encode()).hexdigest()
    return (f'<!-- GENERATED by tools/publish-safety/redact_runbook.py from {src} (sha256 {digest[:16]}). '
            'Do not edit: change the private source and regenerate. -->\n\n')


def unsafe_lines(cfg, text):
    bad = []
    for i, line in enumerate(text.split('\n'), 1):
        cats = {c for c, _ in pc.classify(cfg, line)}
        cats &= pc.BLOCKING | {'host-path', 'private-ip', 'unknown-ip'}
        if cats:
            bad.append((i, sorted(cats)))
    return bad


def build(src, host_rules, cfg, root):
    with open(os.path.join(root, src)) as fh:
        data = fh.read()
    public = header(src, data) + redact(data, host_rules, cfg)
    return public, unsafe_lines(cfg, public)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('pair', nargs='*', help='SRC DEST (default: every pair in public-variants.txt)')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--hosts')
    ap.add_argument('--denylist')
    ap.add_argument('--allowlist', default=pc.DEFAULT_ALLOWLIST)
    ap.add_argument('--generic-only', action='store_true',
                    help='run without the private map and denylist (placeholders are numbered; tests only)')
    ap.add_argument('--root', default=os.path.dirname(os.path.dirname(HERE)))
    args = ap.parse_args(argv)

    class CfgArgs:
        allowlist = args.allowlist
        denylist = args.denylist
        generic_only = args.generic_only
    try:
        cfg = pc.build_config(CfgArgs)
    except SystemExit as why:
        print(why, file=sys.stderr)
        return 2
    hosts = args.hosts or os.environ.get('BLOCH_PUBLISH_HOSTS') or DEFAULT_HOSTS
    if os.path.exists(hosts):
        host_rules = load_hosts(hosts)
    elif args.generic_only:
        host_rules = []
    else:
        print(f'redact_runbook: private host map {hosts} not found (pass --hosts)', file=sys.stderr)
        return 2

    if args.pair:
        if len(args.pair) != 2:
            print('give SRC DEST', file=sys.stderr)
            return 2
        pairs = [tuple(args.pair)]
    else:
        with open(MANIFEST) as fh:
            pairs = [tuple(p.strip() for p in line.split('->')) for line in fh
                     if line.strip() and not line.startswith('#')]
    status = 0
    for src, dest in pairs:
        public, bad = build(src, host_rules, cfg, args.root)
        if bad:
            status = 1
            for i, cats in bad[:20]:
                print(f'{dest}:{i - 2}: still unsafe after redaction: {", ".join(cats)}', file=sys.stderr)
            print(f'{dest}: NOT written ({len(bad)} unsafe lines); extend the host map or the source', file=sys.stderr)
            continue
        dest_path = os.path.join(args.root, dest)
        if args.check:
            current = open(dest_path).read() if os.path.exists(dest_path) else None
            if current != public:
                status = 1
                print(f'{dest}: stale (regenerate from {src})', file=sys.stderr)
            else:
                print(f'{dest}: up to date')
            continue
        os.makedirs(os.path.dirname(dest_path), exist_ok=True)
        with open(dest_path, 'w') as fh:
            fh.write(public)
        print(f'{dest}: written from {src}')
    return status


if __name__ == '__main__':
    sys.exit(main())
